CREATE TABLE article_images (
  article_id BIGINT UNSIGNED NOT NULL,
  image_status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
  prompt_status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
  generation_status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'pending',
  policy_action VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NULL,
  provider VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  model VARCHAR(190) NULL,
  prompt_version VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  prompt_text TEXT NULL,
  fingerprint CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  storage_path VARCHAR(512) NULL,
  mime_type VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  width SMALLINT UNSIGNED NULL,
  height SMALLINT UNSIGNED NULL,
  byte_size INT UNSIGNED NULL,
  source_type VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NULL,
  reused_from_article_id BIGINT UNSIGNED NULL,
  fallback_type VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  retry_count TINYINT UNSIGNED NOT NULL DEFAULT 0,
  force_revision INT UNSIGNED NOT NULL DEFAULT 0,
  worker_id VARCHAR(128) NULL,
  claim_token CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
  claimed_at DATETIME(6) NULL,
  heartbeat_at DATETIME(6) NULL,
  generated_at DATETIME(6) NULL,
  last_error_code VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  last_error_message VARCHAR(1000) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (article_id),
  KEY idx_article_images_work (image_status, heartbeat_at),
  KEY idx_article_images_fingerprint (fingerprint),
  KEY idx_article_images_reused_from (reused_from_article_id),
  CONSTRAINT fk_article_images_article FOREIGN KEY (article_id) REFERENCES articles(id) ON DELETE CASCADE,
  CONSTRAINT fk_article_images_reused_from FOREIGN KEY (reused_from_article_id) REFERENCES articles(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
