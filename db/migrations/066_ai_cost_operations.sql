CREATE TABLE ai_cost_operations (
  operation_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  pilot_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  article_id BIGINT UNSIGNED NOT NULL,
  step_name VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  provider VARCHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  model VARCHAR(128) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  call_kind VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  status VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  usage_date DATE NOT NULL,
  usage_month CHAR(7) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  estimated_input_tokens BIGINT UNSIGNED NOT NULL,
  reserved_output_tokens BIGINT UNSIGNED NOT NULL,
  input_price_micros_per_million BIGINT UNSIGNED NOT NULL,
  output_price_micros_per_million BIGINT UNSIGNED NOT NULL,
  safety_multiplier_millis INT UNSIGNED NOT NULL,
  reserved_cost_micros BIGINT UNSIGNED NOT NULL,
  actual_input_tokens BIGINT UNSIGNED NULL,
  actual_output_tokens BIGINT UNSIGNED NULL,
  actual_cost_micros BIGINT UNSIGNED NULL,
  provider_reported_cost_micros BIGINT UNSIGNED NULL,
  pricing_version VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  started_at DATETIME(6) NULL,
  completed_at DATETIME(6) NULL,
  last_error VARCHAR(1000) NULL,
  created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  PRIMARY KEY (operation_key),
  KEY idx_ai_cost_operations_pilot (pilot_id, status, created_at),
  KEY idx_ai_cost_operations_article (article_id, step_name),
  KEY idx_ai_cost_operations_day (usage_date, status),
  CONSTRAINT fk_ai_cost_operations_article FOREIGN KEY (article_id) REFERENCES articles(id) ON DELETE CASCADE,
  CONSTRAINT chk_ai_cost_operation_kind CHECK (call_kind IN ('chat','embedding')),
  CONSTRAINT chk_ai_cost_operation_status CHECK (status IN ('reserved','started','completed','uncertain'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
